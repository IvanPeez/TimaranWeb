import process from 'node:process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { perfumes } from '../src/services/esenciasBack.js';

// Run explicitly when catalog pictures change. Builds use committed assets and
// never depend on the availability of a third-party image host.
const offline = process.argv.includes('--offline');
const root = new URL('../', import.meta.url);
const output = new URL('resources/optimized/', root);
const cache = new URL('.cache/images/', root);
await mkdir(output, { recursive: true });
await mkdir(cache, { recursive: true });
const hash = (value) => createHash('sha256').update(value).digest('hex').slice(0, 16);
let originalBytes = 0;
let optimizedBytes = 0;
async function source(url) {
  if (!url.startsWith('https:')) return readFile(new URL(url, root));
  const cached = new URL(hash(url), cache);
  try { return await readFile(cached); } catch { /* first download */ }
  if (offline) throw new Error(`No cached source: ${url}`);
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
      if (!response.ok) throw new Error(`HTTP ${response.status}: ${url}`);
      const buffer = Buffer.from(await response.arrayBuffer());
      await sharp(buffer).metadata(); // Reject HTML error pages before caching.
      await writeFile(cached, buffer);
      return buffer;
    } catch (error) {
      if (attempt === 2) throw error;
    }
  }
}
async function optimize(url, name, width, quality = 82) {
  const input = await source(url);
  const buffer = await sharp(input).rotate().resize({ width, withoutEnlargement: true }).webp({ quality }).toBuffer();
  await writeFile(new URL(`${name}.webp`, output), buffer);
  originalBytes += input.length;
  optimizedBytes += buffer.length;
}

