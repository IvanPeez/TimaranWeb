const urls = [...new Set(perfumes.map(p => p.picture).filter(url => url && !/pro-kulturu\.cz|no[-_]?image/i.test(url)))];
let cursor = 0;
let completed = 0;
const failed = [];
await Promise.all(Array.from({ length: 6 }, async () => {
  while (cursor < urls.length) {
    const url = urls[cursor++];
    try {
      // Most catalog originals are 450px wide; keep that detail for sharing.
      await optimize(url, `esencia-${hash(url)}`, 960, 85);
      completed++;
      if (completed % 100 === 0) console.log(`${completed}/${urls.length} catalog images optimized`);
    } catch (error) { failed.push(url); console.error(`${url}: ${error.message}`); }
  }
}));
const available = urls.filter(url => !failed.includes(url));
const imports = available.map((url, i) => `import image${i} from "../../resources/optimized/esencia-${hash(url)}.webp";`).join('\n');
const entries = available.map((url, i) => `  ${JSON.stringify(url)}: image${i},`).join('\n');
await writeFile(new URL('src/services/catalogImages.js', root), `// Generated by npm run images:optimize. Do not edit manually.\n${imports}\n\nexport const catalogImages = {\n${entries}\n};\n`);
await writeFile(new URL('scripts/unavailable-images.json', root), JSON.stringify(urls.filter(url => failed.includes(url)), null, 2) + '\n');
if (failed.length) console.warn(`${failed.length} upstream images unavailable; original URLs retained. See scripts/unavailable-images.json and rerun to retry.`);
